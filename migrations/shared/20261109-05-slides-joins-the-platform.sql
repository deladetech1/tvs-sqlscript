-- Who changed what, when, why, from where. Never updated, and deleted only by activity-log
-- retention (old rows by tenant_id and cdatetime) and the app-data purge after unsubscribe.
-- seq orders the trail: cdatetime can step backwards under a stepped host clock.
CREATE TABLE IF NOT EXISTS slides.sl_audit_logs (
    id           text PRIMARY KEY DEFAULT gen_random_uuid()::text,
    seq          bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id    text NOT NULL,
    org_id       text,
    bus_id       text NOT NULL,
    entity_type  text NOT NULL,
    entity_id    text NOT NULL,
    action       text NOT NULL,
    changes      jsonb NOT NULL DEFAULT '{}',
    reason       text,
    source       text NOT NULL DEFAULT 'ui',
    actor_id     text,
    actor_name   text,
    device_id    text,
    request_id   text,
    cdatetime    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sl_audit_entity_idx
    ON slides.sl_audit_logs (tenant_id, bus_id, entity_type, entity_id, seq DESC);
CREATE INDEX IF NOT EXISTS sl_audit_business_idx
    ON slides.sl_audit_logs (tenant_id, bus_id, seq DESC);

CREATE OR REPLACE FUNCTION slides.sl_audit_logs_append_only() RETURNS trigger
LANGUAGE plpgsql AS $f$
BEGIN
    RAISE EXCEPTION 'sl_audit_logs is append-only: % is not allowed', TG_OP
        USING ERRCODE = 'integrity_constraint_violation';
END
$f$;
DROP TRIGGER IF EXISTS sl_audit_logs_append_only ON slides.sl_audit_logs;
CREATE TRIGGER sl_audit_logs_append_only BEFORE UPDATE ON slides.sl_audit_logs
    FOR EACH ROW EXECUTE FUNCTION slides.sl_audit_logs_append_only();

