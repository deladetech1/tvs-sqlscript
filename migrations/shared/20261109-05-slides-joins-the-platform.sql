-- ===================================================================== invariants
-- Properties only, never counts.
DO $$
DECLARE n int;
BEGIN
    -- 1. Every Slides permission has its pair.
    SELECT count(*) INTO n FROM core_platform.cp_permissions
     WHERE id LIKE 'permission-slides-%' AND (app_prefix <> 'slides' OR resource_key IS NULL OR action IS NULL);
    IF n > 0 THEN
        RAISE EXCEPTION '% Slides permission(s) have no pair; nothing would match them', n;
    END IF;
    -- 2. The Viewer changes nothing.
    SELECT count(*) INTO n FROM core_platform.cp_role_permissions rp
      JOIN core_platform.cp_permissions p ON p.id = rp.permission_id
      JOIN core_platform.cp_actions a ON a.action = p.action
     WHERE rp.role_id = 'role-slides-viewer' AND p.app_prefix = 'slides' AND NOT a.is_read_only;
    IF n > 0 THEN
        RAISE EXCEPTION 'role-slides-viewer holds % Slides permission(s) that change data', n;
    END IF;
    -- 3. Only the Admin (by being the role) manages the whole library.
    IF EXISTS (SELECT 1 FROM core_platform.cp_role_permissions rp JOIN core_platform.cp_permissions p ON p.id = rp.permission_id
                WHERE p.app_prefix = 'slides' AND p.resource_key = 'library') THEN
        RAISE EXCEPTION 'a role holds slides|library|manage; only Slides Admin may, by being the role';
    END IF;
    -- 4. Slides Admin holds no rows of its own app.
    IF EXISTS (SELECT 1 FROM core_platform.cp_role_permissions
                WHERE role_id = 'role-subscribed-app-slides-admin' AND permission_id LIKE 'permission-slides-%') THEN
        RAISE EXCEPTION 'role-subscribed-app-slides-admin holds Slides permission rows';
    END IF;
    -- 5. Every Slides role is named for the app (role_name is unique across apps).
    IF EXISTS (SELECT 1 FROM core_platform.cp_roles
                WHERE (id LIKE 'role-slides-%' OR id = 'role-subscribed-app-slides-admin')
                  AND role_name NOT LIKE 'Slides %') THEN
        RAISE EXCEPTION 'a Slides role has a name that does not start with "Slides"';
    END IF;
    -- 6. Neither address belongs to a tenant, a silo, or is a wildcard.
    IF EXISTS (SELECT 1 FROM control_plane.ctl_tenant_routes
                WHERE host IN ('slides.dev.trovesuite.com', 'api.slides.dev.trovesuite.com')
                  AND (tenant_id IS NOT NULL OR silo_key IS NOT NULL OR is_wildcard)) THEN
        RAISE EXCEPTION 'a Slides address has been given to a tenant or a silo, or made a wildcard';
    END IF;
    -- 7. The label is held, for this app.
    IF NOT EXISTS (SELECT 1 FROM control_plane.ctl_reserved_labels
                    WHERE label = 'slides' AND reason LIKE '%Slides%') THEN
        RAISE EXCEPTION 'the reserved label "slides" does not name the Slides app';
    END IF;
END $$;

