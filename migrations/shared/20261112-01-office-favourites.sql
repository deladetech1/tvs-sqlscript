-- Office R2: favourites (stars). A user stars a file of the library for themself; starring is
-- personal, needs only read access, and is not audited.
--
--   of_favourites  one row per (user, file) starred; seq orders the stars, newest first (the
--                  colima clock steps back, so never order by cdatetime)
--
-- Every row carries tenant_id and bus_id; ids are text uuids, as in 20261110-02. A file's stars go
-- with it (ON DELETE CASCADE) when it is purged. Trash does not touch them: the backend hides a
-- trashed file from view=starred and the star is there again when the file is restored.
-- No grants: the app group's default privileges cover new tables (01-database.md §8). The audit
-- trail (of_audit_logs) is unchanged and no retention or purge registration is needed: the row
-- goes with its file.
-- Design: tvs-shared-apps-bk docs/office-apps/contracts/R2-ux.md §4. Idempotent; safe to re-run.

BEGIN;

-- ======================================================================== favourites
CREATE TABLE IF NOT EXISTS office.of_favourites (
    tenant_id    text NOT NULL,
    bus_id       text NOT NULL,
    user_id      text NOT NULL,
    document_id  text NOT NULL REFERENCES office.of_documents (id) ON DELETE CASCADE,
    cdatetime    timestamptz NOT NULL DEFAULT now(),
    seq          bigint GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT of_favourites_pkey PRIMARY KEY (tenant_id, bus_id, user_id, document_id)
);
-- view=starred: the caller's stars, newest first.
CREATE INDEX IF NOT EXISTS of_favourites_user_idx
    ON office.of_favourites (tenant_id, bus_id, user_id, seq DESC);
-- The cascade on purge finds a file's stars.
CREATE INDEX IF NOT EXISTS of_favourites_document_idx
    ON office.of_favourites (document_id);

COMMIT;
