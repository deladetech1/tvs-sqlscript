-- Sheets (app-sheets) joins the platform: Trovesuite's spreadsheet app. A library of workbooks with a
-- browser editor (a GridCraft fork), one editor at a time behind a lock,
-- versions and a refused stale save. Docs (20261109-01/-02) with a different editor: the same
-- tables, permissions, roles and tiers, with the key swapped. The UI calls one item a workbook;
-- the API, tables and permissions keep the neutral word "documents" so one backend core serves
-- Docs, Sheets and Slides. Never "Excel" (a trademark).
--
-- Served by the shared apps backend (deladetech1/tvs-shared-apps-bk, module "sheets") like Help Desk;
-- frontend tvs-sheets-ft. It is subscribed on its own and needs no other app (not even Docs).
-- Its cp_apps row, tier prices and the role-cp-admin exclusion live in the CorePlatform seed
-- (04_others.sql), which owns every app row. This file holds the rest:
--
--   * the sheets schema and its audit trail (sh_audit_logs, append-only, ordered by seq); the library
--     tables come in 20261109-04;
--   * its cp_app_schemas row, so activity-log retention finds sheets.sh_audit_logs;
--   * resource types, permissions (sheets|<resource>|<action>||any) and the roles: Sheets Admin is
--     allowed by BEING the role and holds no sheets rows; Sheets Editor and Sheets Viewer carry grants;
--   * which features each subscription tier includes (cp_app_feature_catalog);
--   * the reserved label "sheets" (new: nothing held it before) and the route rows for the website
--     and the API.
--
-- Design: tvs-shared-apps-bk docs/office-apps/contracts/R0.md §1-§3, on top of
-- docs/docs-app/contracts/R0.md §1-§4 (the office contract wins where they differ).
-- Nothing here asserts on rows a module seed creates. Idempotent; safe to re-run.

