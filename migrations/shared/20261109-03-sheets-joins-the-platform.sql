        ON CONFLICT (app_id) DO UPDATE SET schema_name = EXCLUDED.schema_name, fate = EXCLUDED.fate, note = EXCLUDED.note;
    END IF;
END $$;

-- ===================================================================== invariants
-- Properties only, never counts.
DO $$
DECLARE n int;
BEGIN
    -- 1. Every Sheets permission has its pair.
    SELECT count(*) INTO n FROM core_platform.cp_permissions
     WHERE id LIKE 'permission-sheets-%' AND (app_prefix <> 'sheets' OR resource_key IS NULL OR action IS NULL);
    IF n > 0 THEN
        RAISE EXCEPTION '% Sheets permission(s) have no pair; nothing would match them', n;
    END IF;
    -- 2. The Viewer changes nothing.
    SELECT count(*) INTO n FROM core_platform.cp_role_permissions rp
      JOIN core_platform.cp_permissions p ON p.id = rp.permission_id
      JOIN core_platform.cp_actions a ON a.action = p.action
     WHERE rp.role_id = 'role-sheets-viewer' AND p.app_prefix = 'sheets' AND NOT a.is_read_only;
    IF n > 0 THEN
        RAISE EXCEPTION 'role-sheets-viewer holds % Sheets permission(s) that change data', n;
    END IF;
    -- 3. Only the Admin (by being the role) manages the whole library.
    IF EXISTS (SELECT 1 FROM core_platform.cp_role_permissions rp JOIN core_platform.cp_permissions p ON p.id = rp.permission_id
                WHERE p.app_prefix = 'sheets' AND p.resource_key = 'library') THEN
        RAISE EXCEPTION 'a role holds sheets|library|manage; only Sheets Admin may, by being the role';
    END IF;
    -- 4. Sheets Admin holds no rows of its own app.
    IF EXISTS (SELECT 1 FROM core_platform.cp_role_permissions
                WHERE role_id = 'role-subscribed-app-sheets-admin' AND permission_id LIKE 'permission-sheets-%') THEN
        RAISE EXCEPTION 'role-subscribed-app-sheets-admin holds Sheets permission rows';
    END IF;
    -- 5. Every Sheets role is named for the app (role_name is unique across apps).
    IF EXISTS (SELECT 1 FROM core_platform.cp_roles
                WHERE (id LIKE 'role-sheets-%' OR id = 'role-subscribed-app-sheets-admin')
                  AND role_name NOT LIKE 'Sheets %') THEN
        RAISE EXCEPTION 'a Sheets role has a name that does not start with "Sheets"';
    END IF;
    -- 6. Neither address belongs to a tenant, a silo, or is a wildcard.
    IF EXISTS (SELECT 1 FROM control_plane.ctl_tenant_routes
                WHERE host IN ('sheets.dev.trovesuite.com', 'api.sheets.dev.trovesuite.com')
                  AND (tenant_id IS NOT NULL OR silo_key IS NOT NULL OR is_wildcard)) THEN
        RAISE EXCEPTION 'a Sheets address has been given to a tenant or a silo, or made a wildcard';
    END IF;
    -- 7. The label is held, for this app.
    IF NOT EXISTS (SELECT 1 FROM control_plane.ctl_reserved_labels
                    WHERE label = 'sheets' AND reason LIKE '%Sheets%') THEN
        RAISE EXCEPTION 'the reserved label "sheets" does not name the Sheets app';
    END IF;
END $$;

