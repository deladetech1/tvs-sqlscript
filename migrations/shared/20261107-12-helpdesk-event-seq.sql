-- Help Desk R7: an insertion sequence on the append-only event, update and conversation tables.
--
--   <table>.seq  a database-assigned increasing number, so a timeline lists its rows in the order
--                they were written, and "the latest" is the last one written. cdatetime (now() or
--                clock_timestamp()) can go backwards when the host's clock is stepped (seen every
--                20 s under colima, by 100-280 ms), so two rows written by separate transactions
--                milliseconds apart could compare out of order: a change's history showed
--                draft > awaiting_approval > draft with the moves the other way round.
--
--   hd_change_events         a change's transitions (change_model.go)
--   hd_ticket_events         a ticket's activity history (messages.go, vendor_routes.go)
--   hd_approval_events       an approval request's history (approval_ticket.go, approval_hooks.go)
--   hd_asset_events          an asset's history (asset_service.go)
--   hd_incident_updates      a major incident's update timeline (major.go)
--   hd_status_events         a status page's incidents and maintenance; "the latest" for a major
--                            incident or a change (status_hooks.go)
--   hd_status_event_updates  a status event's update timeline (status_pages.go)
--   hd_ticket_messages       a ticket's conversation (messages.go, portal.go, cportal_tickets.go)
--   hd_chat_messages         a chat's conversation (chat_routes.go)
--
-- Identity columns, the same as hd_workflow_steps.seq (20261107-11): inserting needs no grant on a
-- sequence. Existing rows are numbered in their stored order. Adding a column does not fire the
-- hd_refuse_change() row triggers. Design: tvs-shared-apps-bk docs/helpdesk/contracts/R7.md §3.
-- Idempotent.

BEGIN;

