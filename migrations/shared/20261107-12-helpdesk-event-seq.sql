    ADD COLUMN IF NOT EXISTS seq bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX IF NOT EXISTS hd_change_events_change_seq_idx ON helpdesk.hd_change_events (change_id, seq);

