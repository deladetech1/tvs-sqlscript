-- CloudHams: roles for every job in a hospital
--
-- CloudHams shipped eleven roles: Medical Director, Doctor, Nurse, Front Desk, Cashier, Billing
-- Officer, Laboratory Scientist, Pharmacist, Operations Officer, Patient Relations Officer and
-- Viewer. A hospital staffs many more jobs than that, and each had to be stacked from those or
-- given Director. These are the jobs themselves, each holding only what the job touches, on the
-- permissions that already exist (no new permissions, so the API needs no change):
--
--   Clinical Officer           consults, diagnoses, orders, prescribes, admits (as a doctor does)
--   Midwife                    the nurse's work, and signs and prescribes in maternity
--   Nurse Manager              the matron or nurse in charge: wards and beds, rosters, nursing quality
--   Radiographer               performs imaging and attaches images; a doctor verifies the report
--   Laboratory Technician      samples and results; the scientist validates and releases them
--   Pharmacy Technician        dispenses and handles stock; the pharmacist sets up medicines and prices
--   Allied Health Professional physio, dietetics, social work, psychology, optometry: notes, no prescribing
--   Blood Bank Officer         donors, screening, blood stock, cross-match and issue
--   Health Information Officer medical records: the index and merges, coding, returns, record requests
--   Insurance Claims Officer   payers, policies and claims
--   Accountant                 prices, bills, invoices, refunds, expenses and the money reports
--   Hospital Administrator     the business side: settings, operations, rosters, quality, money; no clinical record
--   HR & Rostering Officer     duty rosters, leave and training
--   Quality & Infection Control Officer   incidents, audits, infection control, risk, mortality reviews
--   Storekeeper                receiving, issuing, transfers and stock takes
--
-- Every one also has what every CloudHams worker has: the facility profile, messages, tasks and
-- meetings, the rosters to read, and expenses to claim. Roles are given to people in TroveSuite
-- (Users & roles), as the others are. Idempotent; safe to re-run.

