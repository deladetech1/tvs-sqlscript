-- Office (app-office) joins the platform: Trovesuite's office suite. ONE app with three editors --
-- Docs (documents, a WordCraft fork), Sheets (workbooks, GridCraft) and Slides (presentations,
-- DeckCraft) -- over one library: one editor at a time behind a lock, versions and a refused stale
-- save. A business subscribes once, at one price, and its Office Admin switches each editor on or
-- off (office.of_settings, 20261110-02). Which editor opens a file follows from its stored ext.
-- The API, tables and permissions use the neutral word "documents" for a file of any editor.
-- Never "Word", "Excel" or "PowerPoint" (trademarks).
--
-- Served by the shared apps backend (deladetech1/tvs-shared-apps-bk, module "office") like Help
-- Desk; frontend tvs-office-ft. It is subscribed on its own and needs no other app.
-- Its cp_apps row, tier prices and the role-cp-admin exclusion live in the CorePlatform seed
-- (04_others.sql), which owns every app row. This file holds the rest:
--
--   * the office schema and its audit trail (of_audit_logs, append-only, ordered by seq); the
--     library tables and of_settings come in 20261110-02;
--   * its cp_app_schemas row, so activity-log retention finds office.of_audit_logs;
--   * resource types, permissions (office|<resource>|<action>||any) and the roles: Office Admin is
--     allowed by BEING the role and holds no office rows; Office Editor and Office Viewer carry grants;
--   * which features each subscription tier includes (cp_app_feature_catalog);
--   * the reserved label "office" (new) and the route rows for the website and the API.
--
-- It replaces the three R0 apps app-docs, app-sheets and app-slides (20261109-01..06, dev only and
-- never in prod), which 20261110-03 retires.
-- Design: tvs-shared-apps-bk docs/office-apps/contracts/R1-suite.md §1-§3, on top of
-- docs/office-apps/contracts/R0.md and docs/docs-app/contracts/R0.md (R1-suite wins where they differ).
-- Nothing here asserts on rows a module seed creates. Idempotent; safe to re-run.

