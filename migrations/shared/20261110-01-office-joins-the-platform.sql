-- ===================================================================== invariants
-- Properties only, never counts.
DO $$
DECLARE n int;
BEGIN
    -- 1. Every Office permission has its pair.
    SELECT count(*) INTO n FROM core_platform.cp_permissions
     WHERE id LIKE 'permission-office-%' AND (app_prefix <> 'office' OR resource_key IS NULL OR action IS NULL);
    IF n > 0 THEN
        RAISE EXCEPTION '% Office permission(s) have no pair; nothing would match them', n;
    END IF;
    -- 2. The Viewer changes nothing.
    SELECT count(*) INTO n FROM core_platform.cp_role_permissions rp
      JOIN core_platform.cp_permissions p ON p.id = rp.permission_id
      JOIN core_platform.cp_actions a ON a.action = p.action
     WHERE rp.role_id = 'role-office-viewer' AND p.app_prefix = 'office' AND NOT a.is_read_only;
    IF n > 0 THEN
        RAISE EXCEPTION 'role-office-viewer holds % Office permission(s) that change data', n;
    END IF;
    -- 3. Only the Admin (by being the role) manages the whole library.
    IF EXISTS (SELECT 1 FROM core_platform.cp_role_permissions rp JOIN core_platform.cp_permissions p ON p.id = rp.permission_id
                WHERE p.app_prefix = 'office' AND p.resource_key = 'library') THEN
        RAISE EXCEPTION 'a role holds office|library|manage; only Office Admin may, by being the role';
    END IF;
    -- 4. Office Admin holds no rows of its own app.
    IF EXISTS (SELECT 1 FROM core_platform.cp_role_permissions
                WHERE role_id = 'role-subscribed-app-office-admin' AND permission_id LIKE 'permission-office-%') THEN
        RAISE EXCEPTION 'role-subscribed-app-office-admin holds Office permission rows';
    END IF;
    -- 5. Every Office role is named for the app (role_name is unique across apps).
    IF EXISTS (SELECT 1 FROM core_platform.cp_roles
                WHERE (id LIKE 'role-office-%' OR id = 'role-subscribed-app-office-admin')
                  AND role_name NOT LIKE 'Office %') THEN
        RAISE EXCEPTION 'a Office role has a name that does not start with "Office"';
    END IF;
    -- 6. Neither address belongs to a tenant, a silo, or is a wildcard.
    IF EXISTS (SELECT 1 FROM control_plane.ctl_tenant_routes
                WHERE host IN ('office.dev.trovesuite.com', 'api.office.dev.trovesuite.com')
                  AND (tenant_id IS NOT NULL OR silo_key IS NOT NULL OR is_wildcard)) THEN
        RAISE EXCEPTION 'a Office address has been given to a tenant or a silo, or made a wildcard';
    END IF;
    -- 7. The label is held, for this app.
    IF NOT EXISTS (SELECT 1 FROM control_plane.ctl_reserved_labels
                    WHERE label = 'office' AND reason LIKE '%Office%') THEN
        RAISE EXCEPTION 'the reserved label "office" does not name the Office app';
    END IF;
END $$;

