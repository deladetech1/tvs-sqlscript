DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
                WHERE table_schema = 'core_platform' AND table_name = 'cp_apps' AND column_name = 'billing_unit') THEN
        UPDATE core_platform.cp_apps SET billing_unit = 'BUSINESS'
         WHERE id = 'app-docs' AND billing_unit IS DISTINCT FROM 'BUSINESS';
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns
                WHERE table_schema = 'core_platform' AND table_name = 'cp_apps' AND column_name = 'requires_app_id') THEN
        UPDATE core_platform.cp_apps SET requires_app_id = NULL
         WHERE id = 'app-docs' AND requires_app_id IS NOT NULL;
    END IF;
    IF to_regclass('core_platform.cp_app_data_owners') IS NOT NULL THEN
        INSERT INTO core_platform.cp_app_data_owners (app_id, schema_name, fate, note)
        VALUES ('app-docs', 'docs', 'PURGE', 'Docs keeps its data in its own schema (and its blob container) only; nothing is shared with another app.')
        ON CONFLICT (app_id) DO UPDATE SET schema_name = EXCLUDED.schema_name, fate = EXCLUDED.fate, note = EXCLUDED.note;
    END IF;
END $$;

-- ===================================================================== invariants
-- Properties only, never counts.
DO $$
DECLARE n int;
BEGIN
    -- 1. Every Docs permission has its pair.
    SELECT count(*) INTO n FROM core_platform.cp_permissions
     WHERE id LIKE 'permission-docs-%' AND (app_prefix <> 'docs' OR resource_key IS NULL OR action IS NULL);
    IF n > 0 THEN
        RAISE EXCEPTION '% Docs permission(s) have no pair; nothing would match them', n;
    END IF;
    -- 2. The Viewer changes nothing.
    SELECT count(*) INTO n FROM core_platform.cp_role_permissions rp
      JOIN core_platform.cp_permissions p ON p.id = rp.permission_id
      JOIN core_platform.cp_actions a ON a.action = p.action
     WHERE rp.role_id = 'role-docs-viewer' AND p.app_prefix = 'docs' AND NOT a.is_read_only;
    IF n > 0 THEN
        RAISE EXCEPTION 'role-docs-viewer holds % Docs permission(s) that change data', n;
    END IF;
    -- 3. Only the Admin (by being the role) manages the whole library.
    IF EXISTS (SELECT 1 FROM core_platform.cp_role_permissions rp JOIN core_platform.cp_permissions p ON p.id = rp.permission_id
                WHERE p.app_prefix = 'docs' AND p.resource_key = 'library') THEN
        RAISE EXCEPTION 'a role holds docs|library|manage; only Docs Admin may, by being the role';
    END IF;
    -- 4. Docs Admin holds no rows of its own app.
    IF EXISTS (SELECT 1 FROM core_platform.cp_role_permissions
                WHERE role_id = 'role-subscribed-app-docs-admin' AND permission_id LIKE 'permission-docs-%') THEN
        RAISE EXCEPTION 'role-subscribed-app-docs-admin holds Docs permission rows';
    END IF;
    -- 5. Every Docs role is named for the app (role_name is unique across apps).
    IF EXISTS (SELECT 1 FROM core_platform.cp_roles
                WHERE (id LIKE 'role-docs-%' OR id = 'role-subscribed-app-docs-admin')
                  AND role_name NOT LIKE 'Docs %') THEN
        RAISE EXCEPTION 'a Docs role has a name that does not start with "Docs"';
    END IF;
    -- 6. Neither address belongs to a tenant, a silo, or is a wildcard.
    IF EXISTS (SELECT 1 FROM control_plane.ctl_tenant_routes
                WHERE host IN ('docs.dev.trovesuite.com', 'api.docs.dev.trovesuite.com')
                  AND (tenant_id IS NOT NULL OR silo_key IS NOT NULL OR is_wildcard)) THEN
        RAISE EXCEPTION 'a Docs address has been given to a tenant or a silo, or made a wildcard';
    END IF;
    -- 7. The label is held once, for this app.
    IF NOT EXISTS (SELECT 1 FROM control_plane.ctl_reserved_labels
                    WHERE label = 'docs' AND reason LIKE '%Docs%') THEN
        RAISE EXCEPTION 'the reserved label "docs" does not name the Docs app';
    END IF;
END $$;

