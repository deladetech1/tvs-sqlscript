-- Docs (app-docs) joins the platform: Trovesuite's word processor. A document library with a browser
-- editor (a WordCraft fork), one editor at a time behind a lock, versions and a refused stale save.
--
-- Served by the shared apps backend (deladetech1/tvs-shared-apps-bk, module "docs") like Help Desk;
-- frontend tvs-docs-ft. It is subscribed on its own and needs no other app.
-- Its cp_apps row, tier prices and the role-cp-admin exclusion live in the CorePlatform seed
-- (04_others.sql), which owns every app row. This file holds the rest:
--
--   * the docs schema and its audit trail (dc_audit_logs, append-only, ordered by seq); the library
--     tables come in 20261109-02;
--   * its cp_app_schemas row, so activity-log retention finds docs.dc_audit_logs;
--   * resource types, permissions (docs|<resource>|<action>||any) and the roles: Docs Admin is
--     allowed by BEING the role and holds no docs rows; Docs Editor and Docs Viewer carry grants;
--   * which features each subscription tier includes (cp_app_feature_catalog);
--   * the reserved label "docs": 20261005-08 already holds it as "documentation". The owner gave it
--     to this app (2026-11-09), so its reason is updated here; no second row is ever inserted;
--   * the route rows for the website and the API.
--
-- Design: tvs-shared-apps-bk docs/docs-app/contracts/R0.md §1-§4 (it wins over the other documents).
-- Nothing here asserts on rows a module seed creates. Idempotent; safe to re-run.

