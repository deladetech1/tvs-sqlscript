        RAISE WARNING 'cp_permissions rows with no action yet -- add them to the catalogue: %', uncovered;
    END IF;
END $$;

DO $$
DECLARE orphan TEXT;
BEGIN
    SELECT string_agg(DISTINCT p.action, ', ') INTO orphan
    FROM core_platform.cp_permissions p
    LEFT JOIN core_platform.cp_actions a ON a.action = p.action
    WHERE p.action IS NOT NULL AND a.action IS NULL;
    IF orphan IS NOT NULL THEN
        RAISE EXCEPTION 'cp_permissions uses actions absent from cp_actions: %', orphan;
    END IF;
END $$;

-- -------------------------------------------------------------------------------------
-- Now that every row is populated, make the shape enforceable. The FK turns a typo (`aprove`)
-- or a second word for an existing verb (`view` beside `get`) into an error rather than a new
-- verb nobody grants.
--
-- `action` is deliberately left NULLABLE, and the guard above only warns.
--
-- migrations/shared applies in ordinal filename order, so anything added later in the day or on
-- a later date runs AFTER this file -- and LoanDrift migrations are landing daily, inserting
-- permissions with no action. A NOT NULL here would fail the very next one and break somebody
-- else's deploy, not ours. Renumbering this file only postpones that to tomorrow.
--
-- So: populate now, constrain later. Turning on NOT NULL is a separate migration, to be written
-- once the seeds and the app migrations supply `action` themselves. Until then the FK below
-- still rejects a typo'd verb whenever one IS given, which is the guardrail that matters most.
-- -------------------------------------------------------------------------------------

ALTER TABLE core_platform.cp_permissions
    DROP CONSTRAINT IF EXISTS fk_cp_permissions_cp_actions_action;
ALTER TABLE core_platform.cp_permissions
    ADD CONSTRAINT fk_cp_permissions_cp_actions_action
    FOREIGN KEY (action) REFERENCES core_platform.cp_actions (action);

-- One permission per (app, resource, action, target, scope). This is the constraint that would
-- have caught `permission-user-locations-get` sitting beside `permission-user-get-locations` --
-- two ids for one thing, one of them enforced nowhere.
CREATE UNIQUE INDEX IF NOT EXISTS ux_cp_permissions_resource_action
    ON core_platform.cp_permissions (app_prefix, resource_key, action, target, scope)
    WHERE delete_status = 'NOT_DELETED';
