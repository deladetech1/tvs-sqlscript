    action         TEXT PRIMARY KEY,
    label          TEXT      NOT NULL,
    is_read_only   BOOLEAN   NOT NULL DEFAULT false,
    viewer_default BOOLEAN   NOT NULL DEFAULT false,
    cdatetime      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

