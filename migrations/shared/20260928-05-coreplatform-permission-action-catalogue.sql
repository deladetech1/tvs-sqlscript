-- =====================================================================================
-- Give every permission a structured (resource, action, target, scope), and name the verbs.
--
-- Today a permission is one opaque id, and every rule that needs to know what it DOES matches
-- its name: the Viewer Admin trigger carries ~24 `LOWER(permission_name) LIKE '%get%'` clauses.
-- That is why Loandrift Viewer Admin sees every figure in its app ("... Get Statistics") and
-- Mystoreguard Viewer Admin sees none of its thirty ("... Statistics") -- same role, opposite
-- outcome, decided by wording.
--
-- ADDITIVE and INERT. Grants nothing, revokes nothing, changes no permission id and no
-- application code. It records, for each permission, the parts its id was already built from.
--
-- Covers 513 permissions: the 492 in this repo's seeds plus 21 that exist on the
-- database but in no seed file (LoanDrift agreements, collateral, group lending, restructuring,
-- write-off and repayment reversal). Those were created outside tvs-sqlscript and still need to
-- be committed here; they are included so this migration does not refuse to run on a database
-- that already has them, and so the seeds and the database can be reconciled.
--
-- 488 ids recompose exactly from their parts; 25 spell the same parts in a different
-- word order (`user-groups-get` for `user + get + groups`) and keep the id they already have.
-- Safe to rerun.
-- =====================================================================================

SET search_path TO core_platform;

-- -------------------------------------------------------------------------------------
-- The verbs. Written once for the whole suite, so no rule reads a name again.
--
-- is_read_only and viewer_default are deliberately two columns. `reveal` (ZelosHR sensitive
-- fields) is a read a Viewer Admin must NOT receive, and `calculate` persists a credit score
-- despite sounding harmless. Collapsing "is a read" into "safe for a viewer" is the mistake
-- the LIKE '%get%' rule made.
-- -------------------------------------------------------------------------------------
