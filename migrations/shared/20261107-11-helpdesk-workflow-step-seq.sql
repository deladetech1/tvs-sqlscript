-- Help Desk R7: an insertion sequence on workflow steps.
--
--   hd_workflow_steps.seq  a database-assigned increasing number, so the run history lists steps
--                          in the order they were written. cdatetime (clock_timestamp) can go
--                          backwards when the host's clock is stepped (seen every 20 s under
--                          colima), so ordering by it could show an outcome before the step that
--                          led to it. The engine's own "latest step" logic orders by attempt
--                          (workflow_engine.go wfStepLatestOrder) and does not depend on this.
--
-- An identity column: inserting needs no grant on a sequence. Existing rows are numbered in their
-- stored order. Design: tvs-shared-apps-bk docs/helpdesk/contracts/R7.md §3. Idempotent.

BEGIN;

ALTER TABLE helpdesk.hd_workflow_steps
    ADD COLUMN IF NOT EXISTS seq bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX IF NOT EXISTS hd_workflow_steps_run_seq_idx ON helpdesk.hd_workflow_steps (run_id, seq);

COMMIT;
